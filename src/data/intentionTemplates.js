export const getTodayIntention = () => {
  const dayIndex = new Date().getDay();
  return DAILY_INTENTIONS[dayIndex % DAILY_INTENTIONS.length];
};

export const getRandomReflectionPrompt = (type) => {
  const prompts = REFLECTION_PROMPTS[type];
  if (!prompts) return '';
  return prompts[Math.floor(Math.random() * prompts.length)];
};

export const getPostSessionAffirmation = () => {
  return POST_SESSION_AFFIRMATIONS[Math.floor(Math.random() * POST_SESSION_AFFIRMATIONS.length)];
};

